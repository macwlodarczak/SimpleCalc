package logic;

class Calculator {
    public double addTwoNumbers(double a, double b) {
        double sum = a + b;
        return sum;
    }
    public double subsTwoNumbers(double a, double b) {
        double sum = a - b;
        return sum;
    }
    public double multiTwoNumbers(double a, double b) {
        double sum = a * b;
        return sum;
    }
    public double divTwoNumbers(double a, double b) {
        double sum = a / b;
        return sum;
    }
}
